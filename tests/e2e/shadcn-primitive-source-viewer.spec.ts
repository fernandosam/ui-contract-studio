import { test, expect } from "@playwright/test"

test.describe("shadcn: orientação pt-BR e código em gaveta lateral", () => {
  test("Alert mostra orientações traduzidas, código TSX e JSON, e fecha com Escape",async({page})=>{
    await page.goto("/?screen=explorador-primitivos")
    await page.getByLabel("Buscar componente").fill("Alert")
    await page.getByRole("button",{name:"Alert",exact:true}).click()
    const guidance=page.getByTestId("primitive-guidance")
    await expect(guidance).toHaveAttribute("lang","pt-BR")
    await expect(guidance).toContainText("Avisos de sucesso, informação, alerta e erro")
    await expect(guidance).toContainText("AlertTitle resume")
    const toggle=page.getByTestId("primitive-code-toggle-Alert")
    await expect(toggle).toContainText("Ver código")
    await toggle.click()
    const panel=page.getByTestId("primitive-source-panel-Alert")
    await expect(panel).toHaveAttribute("data-side","right")
    await expect(panel.getByTestId("reui-code-block")).toContainText("Alert")
    await panel.getByRole("button",{name:"Exemplo JSON"}).click()
    await expect(panel.getByTestId("reui-code-block")).toContainText('"elements"')
    await page.keyboard.press("Escape")
    await expect(panel).not.toBeVisible()
    await expect(toggle).toBeFocused()
  })
  test("primitiva local sem TSX próprio exibe o exemplo JSON",async({page})=>{
    await page.goto("/?screen=explorador-primitivos")
    await page.getByLabel("Buscar componente").fill("Stack")
    await page.getByRole("button",{name:"Stack",exact:true}).click()
    await expect(page.getByTestId("primitive-guidance")).toContainText("composição local")
    await page.getByTestId("primitive-code-toggle-Stack").click()
    const panel=page.getByTestId("primitive-source-panel-Stack")
    await expect(panel.getByTestId("reui-code-block")).toContainText('"type": "Stack"')
    await panel.getByRole("button",{name:"Fechar código"}).click()
    await expect(panel).not.toBeVisible()
  })
  test("contrato oficial adicional preserva orientações e exibe TSX",async({page})=>{
    await page.goto("/?screen=explorador-primitivos")
    await page.getByLabel("Buscar componente").fill("AspectRatio")
    await page.getByRole("button",{name:"AspectRatio",exact:true}).click()
    await expect(page.getByTestId("primitive-guidance")).toContainText("proporção fixa")
    await page.getByTestId("primitive-code-toggle-AspectRatio").click()
    await expect(page.getByTestId("primitive-source-panel-AspectRatio").getByTestId("reui-code-block")).toContainText("AspectRatio")
  })
})
