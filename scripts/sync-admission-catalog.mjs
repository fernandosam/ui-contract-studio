#!/usr/bin/env node
/** Deterministic promotion of allowlisted, reviewed recipes into the official experimental catalog. */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname } from "node:path";
import { createHash } from "node:crypto";

const read = path => readFileSync(path, "utf8");
const json = path => JSON.parse(read(path));
const digest = contents => createHash("sha256").update(contents).digest("hex");
const policy = json("src/ui-catalog/admission-engine/policy.json");
const protocols = json("src/ui-catalog/admission-engine/protocols.json").candidates;
const recipes = json("scripts/composition-codegen/recipes.json");
const scenarios = json("src/ui-catalog/recommendations/scenarios.json");
const approved = new Set(json("src/ui-catalog/contracts.lock.json").components.map(c => c.name));
const flags = process.argv.slice(2);
const write = flags.includes("--write");
if (flags.some(flag => !["--write", "--check"].includes(flag)) || (write && flags.includes("--check"))) {
  console.error("Use --write or --check"); process.exit(2);
}
const generated = "src/ui-catalog/admission-engine/generated";
const outputs = {};
const rows = [];
const seen = new Set();
const errors = [];
if (policy.schemaVersion !== 1 || policy.mode !== "opt-in-experimental" ||
    !Array.isArray(policy.allowedScenarios) || policy.allowedScenarios.length === 0)
  errors.push("Invalid experimental policy");

for (const id of policy.allowedScenarios ?? []) {
  const recipe = recipes.recipes.find(x => x.id === id);
  const scenario = scenarios.scenarios.find(x => x.id === id);
  if (seen.has(id) || !recipe || !scenario || recipe.review !== "required" ||
      scenario.strategy !== "react-candidate" || recipe.target !== scenario.target ||
      !/^[A-Z][A-Za-z0-9]+$/.test(recipe.target) || approved.has(recipe.target) ||
      scenario.dependencies.some(name => !approved.has(name))) {
    errors.push(id + ": invalid or duplicate/unapproved source"); continue;
  }
  seen.add(id);
  const component = read("scripts/composition-codegen/recipes/" + id + ".component.tsx.txt");
  const schema = read("scripts/composition-codegen/recipes/" + id + ".schema.ts.txt");
  if (!component.includes("PROPOSAL ONLY") || !schema.includes("REVIEW-ONLY") ||
      !schema.includes(".strict()") || /dangerouslySetInnerHTML|(?:fetch|eval|Function)\s*\(/.test(component)) {
    errors.push(id + ": unreviewed or unsafe implementation"); continue;
  }
  outputs[generated + "/" + recipe.componentFile] = component;
  outputs[generated + "/" + recipe.schemaFile] = schema;
  const example = {root:"example",elements:{example:{type:recipe.target,props:recipe.fixtures.valid,children:[]}}};
  outputs["pi-catalog/experimental-examples/" + recipe.target + ".json"] = JSON.stringify(example,null,2) + "\n";
  rows.push({id,type:recipe.target,version:"0.1.0",tier:"composition",
    lifecycle:"experimental",sourceDigest:digest(component+"\n--schema--\n"+schema),
    recipeId:id,source:"scripts/composition-codegen/recipes/"+id,
    example:"pi-catalog/experimental-examples/"+recipe.target+".json",
    events:id.startsWith("alert-")?["confirm"]:[],sourceLicense:"MIT (local composition)",
    e2eProtocol:policy.e2eEligible.includes(id)?protocols[id]?.protocol??null:null,
    exposedToPiExperimental:true});
}
if (errors.length) { errors.forEach(x => console.error("✗ "+x)); process.exit(1); }
const defs = [
  "/* GENERATED by scripts/sync-admission-catalog.mjs; do not hand-edit. */",
  ...rows.map(row => {
    const recipe=recipes.recipes.find(x=>x.id===row.id);
    return 'import {'+recipe.schemaExport+'} from "./'+recipe.schemaFile.slice(0,-3)+'";';
  }),
  "",
  "export const experimentalDefinitions = {",
  ...rows.map(row => {
    const recipe=recipes.recipes.find(x=>x.id===row.id);
    return "  "+recipe.target+": {props:"+recipe.schemaExport+",description:"+
      JSON.stringify("Composição local experimental "+recipe.target+"; sem integração remota ou JSX dinâmico.")+
      (row.events.length?',events:["confirm"] as ["confirm"]':'')+"},";
  }),
  "};", ""
].join("\n");
outputs[generated + "/definitions.ts"] = defs;
const wrappers = [
  "/* GENERATED by scripts/sync-admission-catalog.mjs; do not hand-edit. */",
  ...rows.flatMap(row => {
    const recipe=recipes.recipes.find(x=>x.id===row.id);
    return [
      'import {'+recipe.target+'} from "./'+recipe.componentFile.slice(0,-4)+'";',
      'import type {'+recipe.target+'Props} from "./'+recipe.schemaFile.slice(0,-3)+'";'
    ];
  }),
  "",
  "export const experimentalImplementations = {",
  ...rows.map(row => row.events.length
    ? '  '+row.type+': ({props,emit}:{props:'+row.type+'Props;emit?:(event:"confirm")=>void}) => <'+row.type+' props={props} emit={emit}/>,'
    : '  '+row.type+': ({props}:{props:'+row.type+'Props}) => <'+row.type+' props={props}/>,'),
  "};", ""
].join("\n");
outputs[generated + "/implementations.tsx"] = wrappers;
outputs["src/ui-catalog/admission-engine/entries.json"]=JSON.stringify({schemaVersion:1,entries:rows},null,2)+"\n";
let failures=0;
for (const [path, content] of Object.entries(outputs)) {
  if (write) {mkdirSync(dirname(path),{recursive:true});writeFileSync(path,content);}
  else if (!existsSync(path) || read(path)!==content) {console.error("✗ out of sync: "+path);failures++;}
}
if (failures) process.exit(1);
console.log("✓ "+rows.length+" contracts and "+Object.keys(outputs).length+" generated files "+(write?"written":"verified"));
